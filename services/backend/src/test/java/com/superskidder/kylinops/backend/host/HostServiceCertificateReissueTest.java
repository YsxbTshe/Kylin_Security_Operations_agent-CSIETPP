package com.superskidder.kylinops.backend.host;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

import com.fasterxml.jackson.databind.ObjectMapper;
import com.superskidder.kylinops.backend.common.AppException;
import javax.sql.DataSource;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;

class HostServiceCertificateReissueTest {

    private JdbcTemplate jdbcTemplate;
    private HostService hostService;

    @BeforeEach
    void setUp() {
        DataSource dataSource = new DriverManagerDataSource("jdbc:h2:mem:host-service-reissue;MODE=PostgreSQL;DB_CLOSE_DELAY=-1", "sa", "");
        jdbcTemplate = new JdbcTemplate(dataSource);
        createSchema();
        hostService = new HostService(jdbcTemplate, 180, new ObjectMapper(), null, 600);
    }

    @Test
    void shouldApproveCertificateReissueAndConsumeOneTimeNodeBoundToken() {
        HostCertificateReissueRequest request = hostService.requestCertificateReissue("org-alpha", "host-1", "alice", "lost cert");

        assertThat(request.status()).isEqualTo("PENDING");
        HostCertificateReissueApproval approval = hostService.approveCertificateReissue("org-alpha", request.requestId(), "bob", "approved after device check");

        assertThat(approval.bootstrapToken()).startsWith("reissue-token-");
        assertThat(approval.request().status()).isEqualTo("APPROVED");
        assertThat(approval.request().tokenExpiresAt()).isNotBlank();
        assertThat(hostService.consumeCertificateReissueToken("org-alpha", "node-1", approval.bootstrapToken())).isTrue();
        assertThat(hostService.consumeCertificateReissueToken("org-alpha", "node-1", approval.bootstrapToken())).isFalse();
        assertThat(hostService.consumeCertificateReissueToken("org-alpha", "node-2", approval.bootstrapToken())).isFalse();

        String status = jdbcTemplate.queryForObject(
                "select status from host_agent_certificate_reissue_request where id = ?",
                String.class,
                request.requestId()
        );
        assertThat(status).isEqualTo("CONSUMED");
    }

    @Test
    void shouldRejectDuplicatePendingCertificateReissueRequest() {
        hostService.requestCertificateReissue("org-alpha", "host-1", "alice", "lost cert");

        assertThatThrownBy(() -> hostService.requestCertificateReissue("org-alpha", "host-1", "alice", "again"))
                .isInstanceOf(AppException.class)
                .hasMessageContaining("已有待处理");
    }

    @Test
    void shouldRejectCertificateReissueWithoutToken() {
        HostCertificateReissueRequest request = hostService.requestCertificateReissue("org-alpha", "host-1", "alice", "lost cert");

        HostCertificateReissueRequest rejected = hostService.rejectCertificateReissue("org-alpha", request.requestId(), "bob", "identity mismatch");

        assertThat(rejected.status()).isEqualTo("REJECTED");
        assertThat(hostService.consumeCertificateReissueToken("org-alpha", "node-1", "missing-token")).isFalse();
    }

    private void createSchema() {
        jdbcTemplate.execute("drop table if exists host_agent_certificate_reissue_request");
        jdbcTemplate.execute("drop table if exists agent_runtime_node_session");
        jdbcTemplate.execute("drop table if exists app_managed_host");
        jdbcTemplate.execute("drop table if exists app_organization");
        jdbcTemplate.execute("""
                create table app_organization (
                    id varchar(64) primary key,
                    code varchar(64) not null,
                    name varchar(128) not null
                )
                """);
        jdbcTemplate.execute("""
                create table app_managed_host (
                    id bigint generated by default as identity primary key,
                    organization_id varchar(64) not null,
                    hostname varchar(128) not null,
                    ip varchar(64),
                    status varchar(32),
                    os_version varchar(128),
                    cpu_usage varchar(64),
                    memory_usage varchar(64),
                    disk_usage varchar(64),
                    load_average varchar(64),
                    uptime_text varchar(128),
                    node_id varchar(128),
                    cluster_name varchar(128),
                    agent_version varchar(128),
                    supported_tools_json clob,
                    tool_manifest_json clob,
                    last_heartbeat_at timestamp,
                    grpc_connected boolean,
                    grpc_connected_at timestamp,
                    cert_subject varchar(512),
                    cert_expires_at timestamp,
                    cert_status varchar(32),
                    native_guard_status varchar(32),
                    native_guard_checked_at timestamp,
                    native_guard_critical_count integer,
                    native_guard_warning_count integer,
                    native_guard_json clob,
                    node_exporter_status varchar(32),
                    node_exporter_checked_at timestamp,
                    node_exporter_cpu_usage_percent double precision,
                    node_exporter_memory_usage_percent double precision,
                    node_exporter_filesystem_usage_percent double precision,
                    node_exporter_load1 double precision,
                    node_exporter_json clob
                )
                """);
        jdbcTemplate.execute("""
                create table agent_runtime_node_session (
                    tenant_id varchar(64) not null,
                    node_id varchar(128) not null,
                    native_guard_status varchar(32),
                    native_guard_observed_at timestamp,
                    native_guard_json clob,
                    native_guard_critical_count integer default 0,
                    native_guard_warning_count integer default 0,
                    primary key (tenant_id, node_id)
                )
                """);
        jdbcTemplate.execute("""
                create table host_agent_certificate_reissue_request (
                    id varchar(64) primary key,
                    organization_id varchar(64) not null,
                    node_id varchar(128) not null,
                    hostname varchar(128) not null,
                    requested_by varchar(128) not null,
                    reason varchar(1024),
                    status varchar(32) not null,
                    requested_at timestamp not null,
                    decided_by varchar(128),
                    decided_at timestamp,
                    decision_note varchar(1024),
                    reissue_token_hash varchar(128),
                    reissue_token_expires_at timestamp,
                    reissue_token_consumed_at timestamp,
                    updated_at timestamp not null
                )
                """);
        jdbcTemplate.update("insert into app_organization (id, code, name) values (?, ?, ?)", "org-alpha", "org-alpha", "Org Alpha");
        jdbcTemplate.update("""
                insert into app_managed_host (
                    organization_id, hostname, ip, status, os_version, cpu_usage, memory_usage, disk_usage,
                    load_average, uptime_text, node_id, cluster_name, agent_version, supported_tools_json,
                    grpc_connected, cert_status, native_guard_critical_count, native_guard_warning_count
                ) values (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
                """,
                "org-alpha", "host-1", "127.0.0.1", "OFFLINE", "Kylin", "-", "-", "-",
                "-", "-", "node-1", "cluster-a", "agent", "[]", false, "ACTIVE", 0, 0
        );
    }
}
