package com.superskidder.kylinops.backend.grpc;

import static org.assertj.core.api.Assertions.assertThat;

import com.superskidder.kylinops.backend.cert.NodeIdentitySan;
import com.superskidder.kylinops.backend.nodeexecutor.v2.NodeExecutorControlServiceGrpc;
import io.micrometer.core.instrument.simple.SimpleMeterRegistry;
import java.math.BigInteger;
import java.security.KeyPair;
import java.security.KeyPairGenerator;
import java.security.SecureRandom;
import java.security.cert.X509Certificate;
import java.time.Instant;
import java.time.temporal.ChronoUnit;
import java.util.Date;
import javax.sql.DataSource;
import org.bouncycastle.asn1.x500.X500Name;
import org.bouncycastle.asn1.x509.Extension;
import org.bouncycastle.asn1.x509.GeneralName;
import org.bouncycastle.asn1.x509.GeneralNames;
import org.bouncycastle.cert.jcajce.JcaX509CertificateConverter;
import org.bouncycastle.cert.jcajce.JcaX509v3CertificateBuilder;
import org.bouncycastle.operator.jcajce.JcaContentSignerBuilder;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;

class HostAgentMtlsInterceptorTest {

    private JdbcTemplate jdbcTemplate;
    private SimpleMeterRegistry meterRegistry;
    private HostAgentMtlsInterceptor interceptor;

    @BeforeEach
    void setUp() {
        DataSource dataSource = new DriverManagerDataSource("jdbc:h2:mem:mtls;MODE=PostgreSQL;DB_CLOSE_DELAY=-1", "sa", "");
        jdbcTemplate = new JdbcTemplate(dataSource);
        jdbcTemplate.execute("drop table if exists app_managed_host");
        jdbcTemplate.execute("""
                create table app_managed_host (
                    id bigint generated by default as identity primary key,
                    organization_id varchar(128) not null,
                    node_id varchar(128) not null,
                    cert_status varchar(32),
                    cert_serial_number varchar(128),
                    cert_expires_at timestamp
                )
                """);
        meterRegistry = new SimpleMeterRegistry();
        interceptor = new HostAgentMtlsInterceptor(jdbcTemplate, meterRegistry);
    }

    @Test
    void shouldRejectUnregisteredNodeForAllMethods() {
        HostAgentMtlsIdentity identity = new HostAgentMtlsIdentity("org-1", "node-1", "abc123", "CN=node-1,O=org-1", Instant.now().plusSeconds(3600));

        assertThat(interceptor.peerCertificateAllowed(NodeExecutorControlServiceGrpc.getControlStreamMethod().getFullMethodName(), identity)).isFalse();
        assertThat(interceptor.peerCertificateAllowed(NodeExecutorControlServiceGrpc.getArtifactStreamMethod().getFullMethodName(), identity)).isFalse();
    }

    @Test
    void shouldRequireMatchingSerialForActiveNode() {
        insertHost("org-1", "node-1", "ACTIVE", "abc123", Instant.now().plusSeconds(3600));

        HostAgentMtlsIdentity sameSerial = new HostAgentMtlsIdentity("org-1", "node-1", "abc123", "CN=node-1,O=org-1", Instant.now().plusSeconds(3600));
        HostAgentMtlsIdentity otherSerial = new HostAgentMtlsIdentity("org-1", "node-1", "def456", "CN=node-1,O=org-1", Instant.now().plusSeconds(3600));

        assertThat(interceptor.peerCertificateAllowed(NodeExecutorControlServiceGrpc.getControlStreamMethod().getFullMethodName(), sameSerial)).isTrue();
        assertThat(interceptor.peerCertificateAllowed(NodeExecutorControlServiceGrpc.getArtifactStreamMethod().getFullMethodName(), sameSerial)).isTrue();
        assertThat(interceptor.peerCertificateAllowed(NodeExecutorControlServiceGrpc.getControlStreamMethod().getFullMethodName(), otherSerial)).isFalse();
        assertThat(interceptor.peerCertificateAllowed(NodeExecutorControlServiceGrpc.getArtifactStreamMethod().getFullMethodName(), otherSerial)).isFalse();
    }

    @Test
    void shouldRejectControlMethodsAfterRevocation() {
        insertHost("org-1", "node-1", "REVOKED", "abc123", Instant.now().plusSeconds(3600));

        HostAgentMtlsIdentity sameSerial = new HostAgentMtlsIdentity("org-1", "node-1", "abc123", "CN=node-1,O=org-1", Instant.now().plusSeconds(3600));
        HostAgentMtlsIdentity otherSerial = new HostAgentMtlsIdentity("org-1", "node-1", "def456", "CN=node-1,O=org-1", Instant.now().plusSeconds(3600));

        assertThat(interceptor.peerCertificateAllowed(NodeExecutorControlServiceGrpc.getControlStreamMethod().getFullMethodName(), sameSerial)).isFalse();
        assertThat(interceptor.peerCertificateAllowed(NodeExecutorControlServiceGrpc.getControlStreamMethod().getFullMethodName(), otherSerial)).isFalse();
        assertThat(interceptor.peerCertificateAllowed(NodeExecutorControlServiceGrpc.getArtifactStreamMethod().getFullMethodName(), otherSerial)).isFalse();
    }

    @Test
    void shouldRejectExpiredPeerCertificate() {
        HostAgentMtlsIdentity expired = new HostAgentMtlsIdentity("org-1", "node-1", "abc123", "CN=node-1,O=org-1", Instant.now().minusSeconds(10));

        assertThat(interceptor.peerCertificateAllowed(NodeExecutorControlServiceGrpc.getControlStreamMethod().getFullMethodName(), expired)).isFalse();
        assertThat(interceptor.peerCertificateAllowed(NodeExecutorControlServiceGrpc.getArtifactStreamMethod().getFullMethodName(), expired)).isFalse();
    }

    @Test
    void shouldParseSubjectValues() {
        String subject = "CN=node-1,O=org-1,OU=host";
        assertThat(HostAgentMtlsInterceptor.subjectValue(subject, "CN")).isEqualTo("node-1");
        assertThat(HostAgentMtlsInterceptor.subjectValue(subject, "O")).isEqualTo("org-1");
        assertThat(HostAgentMtlsInterceptor.normalizeSerial("  AB12  ")).isEqualTo("ab12");
    }

    @Test
    void shouldAcceptIdentityFromSubjectAlternativeName() throws Exception {
        X509Certificate certificate = certificate("CN=node-1,O=org-1", NodeIdentitySan.uri("org-1", "node-1"));

        HostAgentMtlsIdentity identity = interceptor.identityFromCertificate(certificate);

        assertThat(identity).isNotNull();
        assertThat(identity.organizationId()).isEqualTo("org-1");
        assertThat(identity.nodeId()).isEqualTo("node-1");
        assertThat(interceptor.cnFallbackCount()).isZero();
    }

    // SAN 是权威身份来源：DN 里的 CN/O 与 SAN 冲突时，一律以 SAN 为准。
    @Test
    void shouldPreferSubjectAlternativeNameOverConflictingSubjectDn() throws Exception {
        X509Certificate certificate = certificate("CN=node-victim,O=org-victim", NodeIdentitySan.uri("org-real", "node-real"));

        HostAgentMtlsIdentity identity = interceptor.identityFromCertificate(certificate);

        assertThat(identity).isNotNull();
        assertThat(identity.organizationId()).isEqualTo("org-real");
        assertThat(identity.nodeId()).isEqualTo("node-real");
        assertThat(interceptor.cnFallbackCount()).isZero();
    }

    // 缺口的核心场景：CA 曾签发过 CN 相同的另一张证书。旧实现读 CN 就会把它当成受害节点；
    // 现在只要证书带 SAN，CN 写什么都没用——哪怕连 serial 都恰好与受害节点在库里的记录一致。
    @Test
    void forgedCommonNameCannotImpersonateNodeWithSan() throws Exception {
        X509Certificate forged = certificate("CN=node-victim,O=org-1", NodeIdentitySan.uri("org-1", "node-attacker"));
        String serial = forged.getSerialNumber().toString(16);
        insertHost("org-1", "node-victim", "ACTIVE", serial, Instant.now().plusSeconds(3600));

        HostAgentMtlsIdentity identity = interceptor.identityFromCertificate(forged);

        assertThat(identity).isNotNull();
        assertThat(identity.nodeId()).isEqualTo("node-attacker");
        assertThat(interceptor.peerCertificateAllowed(
                NodeExecutorControlServiceGrpc.getControlStreamMethod().getFullMethodName(), identity)).isFalse();
    }

    // 存量证书（本改动之前签发）没有 SAN：必须仍能接入，但要留下 WARN 与计数供运维判断迁移进度。
    @Test
    void shouldFallBackToSubjectDnWhenSanIsMissingAndCountIt() throws Exception {
        X509Certificate legacy = certificate("CN=node-legacy,O=org-1", null);

        HostAgentMtlsIdentity identity = interceptor.identityFromCertificate(legacy);

        assertThat(identity).isNotNull();
        assertThat(identity.organizationId()).isEqualTo("org-1");
        assertThat(identity.nodeId()).isEqualTo("node-legacy");
        assertThat(interceptor.cnFallbackCount()).isEqualTo(1.0);
        assertThat(meterRegistry.get("kylin.backend.mtls.identity.cn_fallback").counter().count()).isEqualTo(1.0);
    }

    // 非本平台的 URI SAN（例如运维自签的 https:// SAN）不算身份，仍然走回退而不是被误读。
    @Test
    void shouldIgnoreForeignUriSanAndFallBack() throws Exception {
        X509Certificate certificate = certificate("CN=node-legacy,O=org-1", "https://example.com/node");

        HostAgentMtlsIdentity identity = interceptor.identityFromCertificate(certificate);

        assertThat(identity).isNotNull();
        assertThat(identity.nodeId()).isEqualTo("node-legacy");
        assertThat(interceptor.cnFallbackCount()).isEqualTo(1.0);
    }

    // 一张证书带两个不同的平台身份只能是签发事故或构造证书：拒绝，不"取第一个"。
    @Test
    void shouldRejectCertificateWithConflictingIdentitySans() throws Exception {
        X509Certificate certificate = certificate(
                "CN=node-1,O=org-1",
                NodeIdentitySan.uri("org-1", "node-1"),
                NodeIdentitySan.uri("org-1", "node-2")
        );

        assertThat(interceptor.identityFromCertificate(certificate)).isNull();
        assertThat(meterRegistry.get("kylin.backend.mtls.identity.san_rejected").counter().count()).isEqualTo(1.0);
    }

    @Test
    void shouldRejectCertificateWithNeitherSanNorUsableSubjectDn() throws Exception {
        X509Certificate certificate = certificate("OU=nothing-useful", null);

        assertThat(interceptor.identityFromCertificate(certificate)).isNull();
    }

    private X509Certificate certificate(String subjectDn, String... sanUris) throws Exception {
        KeyPairGenerator generator = KeyPairGenerator.getInstance("RSA");
        generator.initialize(2048);
        KeyPair keyPair = generator.generateKeyPair();
        Instant now = Instant.now();
        X500Name subject = new X500Name(subjectDn);
        JcaX509v3CertificateBuilder builder = new JcaX509v3CertificateBuilder(
                subject,
                new BigInteger(64, new SecureRandom()),
                Date.from(now.minus(1, ChronoUnit.MINUTES)),
                Date.from(now.plus(1, ChronoUnit.DAYS)),
                subject,
                keyPair.getPublic()
        );
        GeneralName[] names = java.util.Arrays.stream(sanUris == null ? new String[0] : sanUris)
                .filter(java.util.Objects::nonNull)
                .map(uri -> new GeneralName(GeneralName.uniformResourceIdentifier, uri))
                .toArray(GeneralName[]::new);
        if (names.length > 0) {
            builder.addExtension(Extension.subjectAlternativeName, false, new GeneralNames(names));
        }
        return new JcaX509CertificateConverter().getCertificate(
                builder.build(new JcaContentSignerBuilder("SHA256withRSA").build(keyPair.getPrivate())));
    }

    private void insertHost(String organizationId, String nodeId, String status, String serialNumber, Instant expiresAt) {
        jdbcTemplate.update("""
                insert into app_managed_host (organization_id, node_id, cert_status, cert_serial_number, cert_expires_at)
                values (?, ?, ?, ?, ?)
                """,
                organizationId,
                nodeId,
                status,
                serialNumber,
                java.sql.Timestamp.from(expiresAt)
        );
    }
}
