package com.superskidder.kylinops.backend.host;

import static org.assertj.core.api.Assertions.assertThat;

import com.fasterxml.jackson.databind.ObjectMapper;
import java.time.Instant;
import javax.sql.DataSource;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;

class HostServiceEnrollmentTest {

    private JdbcTemplate jdbcTemplate;
    private HostService hostService;

    @BeforeEach
    void setUp() {
        DataSource dataSource = new DriverManagerDataSource("jdbc:h2:mem:host-enroll;MODE=PostgreSQL;DB_CLOSE_DELAY=-1", "sa", "");
        jdbcTemplate = new JdbcTemplate(dataSource);
        jdbcTemplate.execute("drop table if exists app_managed_host");
        jdbcTemplate.execute("drop table if exists app_organization");
        jdbcTemplate.execute("""
                create table app_organization (
                    id varchar(64) primary key,
                    code varchar(64) not null,
                    name varchar(128) not null
                )
                """);
        jdbcTemplate.execute("""
                create table app_managed_host (
                    id bigint generated by default as identity primary key,
                    organization_id varchar(64) not null,
                    hostname varchar(128) not null,
                    ip varchar(64),
                    status varchar(32),
                    os_version varchar(128),
                    cpu_usage varchar(64),
                    memory_usage varchar(64),
                    disk_usage varchar(64),
                    load_average varchar(64),
                    uptime_text varchar(128),
                    node_id varchar(128),
                    cluster_name varchar(128),
                    agent_version varchar(128),
                    supported_tools_json clob,
                    tool_manifest_json clob,
                    last_heartbeat_at timestamp,
                    grpc_connected boolean,
                    grpc_connected_at timestamp,
                    cert_subject varchar(512),
                    cert_expires_at timestamp,
                    cert_serial_number varchar(128),
                    cert_status varchar(32),
                    cert_issued_at timestamp,
                    cert_revoked_at timestamp,
                    cert_revocation_reason varchar(512),
                    native_guard_status varchar(32),
                    native_guard_checked_at timestamp,
                    native_guard_critical_count integer default 0,
                    native_guard_warning_count integer default 0,
                    native_guard_json clob
                )
                """);
        jdbcTemplate.update("insert into app_organization (id, code, name) values (?, ?, ?)", "org-alpha", "org-alpha", "Org Alpha");
        hostService = new HostService(jdbcTemplate, 180, new ObjectMapper(), null, 600);
    }

    @Test
    void enrollCreatesActiveHostRowWithCertificateBinding() {
        Instant expires = Instant.now().plusSeconds(3600);
        assertThat(hostService.recordEnrollment(
                "org-alpha", "node-kylin-01", "kylin-node-01",
                "CN=node-kylin-01, O=org-alpha, OU=kylin-node-01",
                "ABC123",
                expires
        )).isTrue();

        String status = jdbcTemplate.queryForObject(
                "select cert_status from app_managed_host where organization_id = ? and node_id = ?",
                String.class, "org-alpha", "node-kylin-01"
        );
        String serial = jdbcTemplate.queryForObject(
                "select cert_serial_number from app_managed_host where organization_id = ? and node_id = ?",
                String.class, "org-alpha", "node-kylin-01"
        );
        assertThat(status).isEqualTo("ACTIVE");
        assertThat(serial).isEqualTo("abc123");
    }

    @Test
    void enrollIsIdempotentAndRefreshesSerial() {
        Instant expires = Instant.now().plusSeconds(3600);
        hostService.recordEnrollment("org-alpha", "node-1", "host-1", "CN=node-1", "aaa", expires);
        hostService.recordEnrollment("org-alpha", "node-1", "host-1", "CN=node-1", "BBB", expires);

        Integer count = jdbcTemplate.queryForObject("select count(1) from app_managed_host", Integer.class);
        String serial = jdbcTemplate.queryForObject(
                "select cert_serial_number from app_managed_host where node_id = ?",
                String.class, "node-1"
        );
        assertThat(count).isEqualTo(1);
        assertThat(serial).isEqualTo("bbb");
    }

    @Test
    void enrollRejectsUnknownTenant() {
        assertThat(hostService.recordEnrollment(
                "missing-org", "node-1", "host-1", "CN=node-1", "abc", Instant.now()
        )).isFalse();
    }
}
